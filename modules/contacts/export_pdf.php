<?php
// Server-side export to PDF for contacts (mPDF)
use Mpdf\Mpdf;
use Mpdf\Config\ConfigVariables;
use Mpdf\Config\FontVariables;
if (!defined('CRM_CONFIG')) {
    require_once __DIR__ . '/../../config/config.php';
}

require_login();
require_once __DIR__ . '/../../includes/functions.php';

// Composer autoload (mPDF)
$autoload = __DIR__ . '/../../vendor/autoload.php';
if (file_exists($autoload)) {
    require_once $autoload;
}

// Check for mPDF
if (!class_exists('Mpdf\\Mpdf')) {
    header('Content-Type: text/plain; charset=utf-8');
    echo "mPDF is not installed.\nRun: composer require mpdf/mpdf\n";
    exit;
}

try {
    $db = get_db();
    $rows = $db->fetchAll("SELECT c.id, c.first_name, c.last_name, c.email, c.phone, c.company, c.type, u.full_name as assigned_name, c.created_at FROM contacts c LEFT JOIN users u ON c.assigned_to = u.id ORDER BY c.created_at DESC");

    // Build HTML with advanced styling: header, footer, table with column widths and zebra rows
    $html = '<!doctype html><html><head><meta charset="utf-8"><style>';

    // Try to use an Arabic TTF from assets/fonts if present
    $fontFile = realpath(__DIR__ . '/../../assets/fonts/Amiri-Regular.ttf') ?: realpath(__DIR__ . '/../../assets/fonts/NotoNaskhArabic-Regular.ttf');
    if ($fontFile && file_exists($fontFile)) {
        $fontUrl = str_replace('\\', '/', $fontFile);
        if (stripos(PHP_OS, 'WIN') === 0 && substr($fontUrl,0,1) !== '/') {
            $fontUrl = '/' . $fontUrl; // file URI requires leading slash on Windows
        }
        $fontUrl = 'file://' . $fontUrl;
        $html .= "@font-face{font-family: 'ArabicFont'; src: url('$fontUrl');}";
        $bodyFont = "'ArabicFont', 'DejaVu Sans', sans-serif";
        $fontFound = true;
    } else {
        $bodyFont = "'DejaVu Sans', sans-serif";
    }

    $html .= '@page { size: A4 landscape; margin: 18mm 12mm 18mm 12mm; }';
    $html .= 'body { font-family: ' . $bodyFont . '; direction: rtl; font-size:12px; color:#222; }';
    $html .= 'header { position: fixed; top: -10mm; left: 0; right:0; height:28mm; text-align:center; }';
    $html .= 'footer { position: fixed; bottom: -10mm; left: 0; right:0; height:18mm; text-align:center; font-size:10px; color:#666 }';
    $html .= 'table{width:100%;border-collapse:collapse;margin-top:6mm}';
    $html .= 'th,td{border:1px solid #ddd;padding:6px;text-align:right;vertical-align:top}';
    $html .= 'thead th{background:#f1f5f9;padding:8px;font-weight:700}';
    $html .= '.title{font-size:16px;text-align:center;margin:0;padding:0}';
    $html .= '.meta{font-size:11px;color:#666;margin-top:4px}';
    $html .= '.small{font-size:10px;color:#666}';
    $html .= '.logo{float:left;height:36px}';
    $html .= '.nowrap{white-space:nowrap}';
    $html .= '.col-name{width:28%}.col-email{width:20%}.col-phone{width:12%}.col-company{width:18%}.col-type{width:8%}.col-assigned{width:10%}.col-date{width:12%}';
    $html .= '</style></head><body>';

    // Header
    $html .= '<header><div class="title">' . htmlspecialchars(APP_NAME) . ' - قائمة جهات الاتصال</div><div class="meta">تاريخ التصدير: ' . date('Y-m-d H:i:s') . '</div></header>';
    // Footer placeholder (page numbers will be added via canvas)
    $html .= '<footer><div class="small">Generated by ' . htmlspecialchars(APP_NAME) . '</div></footer>';

    $html .= '<main>';
    $html .= '<table><thead><tr>';
    $headers = ['الاسم','البريد الإلكتروني','الهاتف','الشركة','النوع','المسؤول','تاريخ الإنشاء'];
    foreach ($headers as $h) { $html .= '<th>' . $h . '</th>'; }
    $html .= '</tr></thead><tbody>';

    foreach ($rows as $r) {
        $name = htmlspecialchars(trim(($r['first_name'] ?? '') . ' ' . ($r['last_name'] ?? '')));
        $html .= '<tr>';
        $html .= '<td>' . $name . '</td>';
        $html .= '<td>' . htmlspecialchars($r['email'] ?? '') . '</td>';
        $html .= '<td>' . htmlspecialchars($r['phone'] ?? '') . '</td>';
        $html .= '<td>' . htmlspecialchars($r['company'] ?? '') . '</td>';
        $html .= '<td>' . htmlspecialchars($r['type_label'] ?? ($r['type'] ?? '')) . '</td>';
        $html .= '<td>' . htmlspecialchars($r['assigned_name'] ?? '') . '</td>';
        $html .= '<td>' . htmlspecialchars($r['created_at'] ?? '') . '</td>';
        $html .= '</tr>';
    }

    $html .= '</tbody></table></main></body></html>';

    // Configure mPDF with custom font directory and font data
    $defaultConfig = (new ConfigVariables())->getDefaults();
    $fontDirs = $defaultConfig['fontDir'];
    $defaultFontConfig = (new FontVariables())->getDefaults();
    $fontData = $defaultFontConfig['fontdata'];

    $localFontDir = realpath(__DIR__ . '/../../assets/fonts') ?: (__DIR__ . '/../../assets/fonts');

    // Register the downloaded Noto Naskh Arabic font if present
    $mpdfFontKey = 'notonaskharabic';
    $registeredFont = [];
    if (file_exists($localFontDir . '/NotoNaskhArabic-Regular.ttf')) {
        $registeredFont[$mpdfFontKey] = [
            'R' => 'NotoNaskhArabic-Regular.ttf',
            'useOTL' => 0xFF,
            'useKashida' => 75,
        ];
    } elseif (!empty($fontFound)) {
        // If we registered ArabicFont earlier for Dompdf fallback, use it name
        // copy PHP-detected font filename into mPDF font data if possible
        $registeredFont[$mpdfFontKey] = [
            'R' => basename($fontFile),
            'useOTL' => 0xFF,
            'useKashida' => 75,
        ];
    }

    $hasCustomFont = !empty($registeredFont);
    $defaultFont = $hasCustomFont ? $mpdfFontKey : 'dejavusans';

    $mpdf = new Mpdf([
        'mode' => 'utf-8',
        'format' => 'A4-L',
        'fontDir' => array_merge($fontDirs, [$localFontDir]),
        'fontdata' => $fontData + ($hasCustomFont ? $registeredFont : []),
        'default_font' => $defaultFont,
    ]);

    // Improve automatic script/lang/font handling for Arabic
    $mpdf->autoScriptToLang = true;
    $mpdf->autoLangToFont = true;

    // Ensure right-to-left direction and UTF-8
    $mpdf->SetDirectionality('rtl');

    // Add footer with page numbers
    $mpdf->SetHTMLFooter('<div style="text-align:center;font-size:10px;color:#666">الصفحة {PAGENO} من {nbpg}</div>');

    // Write and output PDF
    $mpdf->WriteHTML($html);
    $filename = preg_replace('/[^A-Za-z0-9\\-_]/', '_', APP_NAME) . '_contacts.pdf';
    $mpdf->Output($filename, 'D');
    exit;

} catch (Exception $e) {
    error_log('Export PDF error: ' . $e->getMessage());
    http_response_code(500);
    echo 'خطأ في إنشاء ملف PDF. راجع سجل الأخطاء.';
}

?>
